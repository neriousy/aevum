const dictionaries: Record<UiLanguage, Record<MessageKey, string>> = {
  en,
  pl,
  "zh-Hans": zhHans,
};

export const UI_LANGUAGES: Array<{ id: UiLanguage; labelKey: MessageKey }> = [
  { id: "en", labelKey: "language.english" },
  { id: "pl", labelKey: "language.polish" },
  { id: "zh-Hans", labelKey: "language.chinese" },
];

export type Translator = (key: MessageKey, variables?: Record<string, string | number>) => string;

export function createTranslator(language: UiLanguage): Translator {
  const messages = dictionaries[language] ?? en;
  return (key, variables = {}) =>
    Object.entries(variables).reduce(
      (message, [name, value]) => message.replaceAll(`{{${name}}}`, String(value)),
      messages[key] ?? en[key],
    );
}
